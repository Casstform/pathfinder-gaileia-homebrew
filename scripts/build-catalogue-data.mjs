import fs from "node:fs";

const outputPath = "assets/js/catalogue-data.js";
const checkOnly = process.argv.includes("--check");

function readJson(path) {
  return JSON.parse(fs.readFileSync(path, "utf8"));
}

const entriesDocument = readJson("content/entries.json");
const collectionsDocument = readJson("content/collections.json");
const referenceLinksDocument = readJson("content/reference-links.json");

for (const [name, document] of Object.entries({
  entries: entriesDocument,
  collections: collectionsDocument,
  referenceLinks: referenceLinksDocument
})) {
  if (document.schemaVersion !== 1) {
    throw new Error(`${name} uses unsupported schema version ${document.schemaVersion}`);
  }
}

const generated = `// Generated by scripts/build-catalogue-data.mjs. Edit content/*.json instead.\n(function () {\n  "use strict";\n\n  window.HOMEBREW_ENTRIES = ${JSON.stringify(entriesDocument.entries, null, 2)};\n\n  const collectionsConfig = ${JSON.stringify(collectionsDocument, null, 2)};\n  window.GAILEIA_COLLECTIONS_CONFIG = collectionsConfig;\n  window.HOMEBREW_CATEGORIES = collectionsConfig.collections.map((collection) => collection.name);\n  window.GAILEIA_CATEGORY_SYMBOLS = Object.fromEntries(\n    collectionsConfig.collections\n      .filter((collection) => collection.symbol)\n      .map((collection) => [collection.name, collection.symbol])\n  );\n\n  window.GAILEIA_TRAIT_URLS = ${JSON.stringify(referenceLinksDocument.traitUrls, null, 2)};\n  window.GAILEIA_RULE_LINKS = ${JSON.stringify(referenceLinksDocument.ruleLinks, null, 2)};\n\n  window.GAILEIA_ADVANCED_ALCHEMY = {\n    defaultLevel: collectionsConfig.advancedAlchemy.defaultLevel,\n    slotsForLevel(level) {\n      return collectionsConfig.advancedAlchemy.baseSlots +\n        Math.ceil(level / collectionsConfig.advancedAlchemy.levelDivisor);\n    }\n  };\n\n  window.GAILEIA_FORMULA_FILTERS = {\n    options: collectionsConfig.formulaFilters.options.map(({ id, label }) => ({ id, label })),\n    matches(entry, selectedFilters) {\n      if (entry.category !== "Formulae") return true;\n      const filters = selectedFilters instanceof Set\n        ? [...selectedFilters]\n        : Array.isArray(selectedFilters)\n          ? selectedFilters\n          : selectedFilters && selectedFilters !== "all"\n            ? [selectedFilters]\n            : [];\n      if (filters.length === 0 || filters.includes("all")) return true;\n\n      const optionById = Object.fromEntries(\n        collectionsConfig.formulaFilters.options.map((option) => [option.id, option])\n      );\n      const methodFilters = filters.filter((filter) => optionById[filter]?.group === "method");\n      const ownerFilters = filters.filter((filter) => optionById[filter]?.group === "owner");\n      const methodMatches = methodFilters.length === 0 || methodFilters.some((filter) => {\n        const field = collectionsConfig.formulaFilters.methodFields[filter];\n        return field ? Boolean(entry[field]) : false;\n      });\n      const ownerMatches = ownerFilters.length === 0 || ownerFilters.some((filter) =>\n        Array.isArray(entry.formulaOwners) && entry.formulaOwners.some(\n          (owner) => owner.toLocaleLowerCase() === filter\n        )\n      );\n      return methodMatches && ownerMatches;\n    }\n  };\n})();\n`;

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error(`${outputPath} is stale. Run: node scripts/build-catalogue-data.mjs`);
    process.exit(1);
  }
  console.log("Generated catalogue data is current.");
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`Wrote ${outputPath}.`);
}
